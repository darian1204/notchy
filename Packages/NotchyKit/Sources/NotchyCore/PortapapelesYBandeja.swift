import Foundation

/// Categorías de elementos que guarda el portapapeles (CLP-1, CLP-3).
public enum TipoDePortapapeles: String, Codable, Sendable, CaseIterable, Equatable {
    case texto
    case enlace
    case imagen
    case archivo

    public var etiqueta: String {
        switch self {
        case .texto: "Texto"
        case .enlace: "Enlaces"
        case .imagen: "Imágenes"
        case .archivo: "Archivos"
        }
    }

    public var icono: String {
        switch self {
        case .texto: "doc.text"
        case .enlace: "link"
        case .imagen: "photo"
        case .archivo: "folder"
        }
    }
}

/// Elemento guardado en el historial del portapapeles.
public struct ElementoDePortapapeles: Sendable, Equatable, Identifiable, Codable {
    public let id: String
    public let creado: Date
    public let tipo: TipoDePortapapeles
    public let texto: String
    public let rutaArchivo: String?
    public let huella: String
    public let appOrigen: String?
    public let bundleOrigen: String?
    public var fijado: Bool
    public let bytes: Int

    public init(
        id: String = UUID().uuidString,
        creado: Date = .now,
        tipo: TipoDePortapapeles,
        texto: String,
        rutaArchivo: String? = nil,
        huella: String,
        appOrigen: String? = nil,
        bundleOrigen: String? = nil,
        fijado: Bool = false,
        bytes: Int
    ) {
        self.id = id
        self.creado = creado
        self.tipo = tipo
        self.texto = texto
        self.rutaArchivo = rutaArchivo
        self.huella = huella
        self.appOrigen = appOrigen
        self.bundleOrigen = bundleOrigen
        self.fijado = fijado
        self.bytes = bytes
    }

    /// Texto legible para chips y tarjetas de resumen, incluso si es imagen o archivo sin texto.
    public var resumenCorto: String {
        let limpio = texto.trimmingCharacters(in: .whitespacesAndNewlines)
        if tipo == .texto || tipo == .enlace {
            return limpio.isEmpty ? tipo.etiqueta : limpio
        }
        if !limpio.isEmpty { return limpio }
        if let rutaArchivo, !rutaArchivo.isEmpty {
            let nombre = URL(fileURLWithPath: rutaArchivo).lastPathComponent
            if !nombre.isEmpty { return nombre }
        }
        return tipo == .imagen ? "Imagen" : "Archivo"
    }
}

/// Lectura cruda del portapapeles del sistema antes de decidir si se guarda.
public enum CargaDePortapapeles: Sendable, Equatable {
    case sensible
    case vacia
    case texto(String)
    case archivos([URL])
    case imagenPNG(Data)
}

public struct MuestraDePortapapeles: Sendable, Equatable {
    public let conteo: Int
    public let tipos: [String]
    public let appOrigen: String?
    public let bundleOrigen: String?
    public let carga: CargaDePortapapeles

    public init(
        conteo: Int,
        tipos: [String],
        appOrigen: String? = nil,
        bundleOrigen: String? = nil,
        carga: CargaDePortapapeles
    ) {
        self.conteo = conteo
        self.tipos = tipos
        self.appOrigen = appOrigen
        self.bundleOrigen = bundleOrigen
        self.carga = carga
    }
}

/// Puerto para vigilar y escribir en el portapapeles del sistema (CLP-1, CLP-2, CLP-4, CLP-7).
@MainActor
public protocol PuertoDePortapapeles: AnyObject {
    /// Tipos que marcan contenido *concealed*, *transient* o autogenerado que nunca debe guardarse (CLP-2).
    static var tiposSensibles: Set<String> { get }

    var conteoDeCambios: Int { get }
    func leerActual() -> MuestraDePortapapeles
    @discardableResult
    func escribir(_ elemento: ElementoDePortapapeles) -> Int
    func limpiar()
}

extension PuertoDePortapapeles {
    public static var tiposSensibles: Set<String> {
        [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "com.1password.1password",
            "de.petermaurer.TransientPasteboardType",
            "com.typeit4me.clipping",
            "Pasteboard generator type",
        ]
    }
}

/// Se publica cuando el portapapeles registra un elemento nuevo (lo escucha Inicio).
public struct ElementoDePortapapelesAgregado: Evento, Equatable {
    public let elemento: ElementoDePortapapeles

    public init(elemento: ElementoDePortapapeles) {
        self.elemento = elemento
    }
}

/// Elemento guardado en la bandeja de archivos (BND-1 a BND-3).
public struct ElementoDeBandeja: Sendable, Equatable, Identifiable, Codable {
    public let id: String
    public let creado: Date
    public let nombre: String
    public let rutaOriginal: String
    public let rutaCopia: String
    public let bytes: Int

    public init(
        id: String = UUID().uuidString,
        creado: Date = .now,
        nombre: String,
        rutaOriginal: String,
        rutaCopia: String,
        bytes: Int
    ) {
        self.id = id
        self.creado = creado
        self.nombre = nombre
        self.rutaOriginal = rutaOriginal
        self.rutaCopia = rutaCopia
        self.bytes = bytes
    }

    public var urlParaArrastrar: URL {
        if FileManager.default.fileExists(atPath: rutaCopia) {
            return URL(fileURLWithPath: rutaCopia)
        }
        return URL(fileURLWithPath: rutaOriginal)
    }

    public var archivoDisponible: Bool {
        FileManager.default.fileExists(atPath: rutaCopia) || FileManager.default.fileExists(atPath: rutaOriginal)
    }
}
